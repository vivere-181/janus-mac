import AppKit
import SwiftUI

/// The last things copied on this Mac, including what arrives from the phone (the engine puts phone
/// copies on the Mac clipboard). Kept in memory only; passwords and other concealed items are skipped.
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 25

    struct Item: Identifiable, Equatable {
        enum Kind { case text, link, image }
        let id = UUID()
        let kind: Kind
        let text: String            // text, link, or a short image description
        let image: NSImage?
        let imageData: Data?        // PNG, to copy it back
        var date = Date()

        static func == (a: Item, b: Item) -> Bool { a.id == b.id }
    }

    private(set) var items: [Item] = []
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var ownWrite = -1

    static var enabled: Bool { UserDefaults.standard.object(forKey: "clipboard.history") as? Bool ?? true }

    /// Types that password managers and similar tools use to say "don't record this".
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    func start() {
        guard timer == nil else { return }
        // The clipboard has no change notification; comparing a counter once a second costs nothing.
        let t = Timer(timeInterval: 1, repeats: true) { _ in MainActor.assumeIsolated { self.check() } }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Self.enabled, pb.changeCount != ownWrite else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }

        if let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            let isLink = URL(string: text).map { ["http", "https"].contains($0.scheme ?? "") } ?? false
            add(Item(kind: isLink ? .link : .text, text: String(text.prefix(5000)), image: nil, imageData: nil))
        } else if !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
                  let image = NSImage(pasteboard: pb),
                  let tiff = image.tiffRepresentation, tiff.count < 40_000_000,
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            let size = image.size
            add(Item(kind: .image, text: "Image · \(Int(size.width))×\(Int(size.height))", image: image, imageData: png))
        }
    }

    private func add(_ item: Item) {
        // Copying the same text again moves it to the top instead of repeating it.
        if item.kind != .image { items.removeAll { $0.kind != .image && $0.text == item.text } }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts an item back on the clipboard (the engine then sends it to the phone as usual).
    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let data = item.imageData {
            pb.setData(data, forType: .png)
        } else {
            pb.setString(item.text, forType: .string)
        }
        ownWrite = pb.changeCount
        if let i = items.firstIndex(of: item) {
            var moved = items.remove(at: i)
            moved.date = .now
            items.insert(moved, at: 0)
        }
    }

    func send(_ item: Item, to device: Device) {
        if let data = item.imageData {
            let url = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
                .appendingPathComponent("Android/Outgoing/Clipboard \(item.date.formatted(.iso8601.year().month().day().time(includingFractionalSeconds: false).timeSeparator(.omitted))).png")
            try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            if (try? data.write(to: url)) != nil { device.share([url]) }
        } else {
            device.shareText(item.text)
        }
    }

    func remove(_ item: Item) { items.removeAll { $0 == item } }
    func clear() { items.removeAll() }
}

/// One history item: icon or thumbnail, the text, and when it was copied.
struct ClipboardItemRow: View {
    let item: ClipboardHistory.Item
    var compact = false

    var body: some View {
        HStack(spacing: 10) {
            thumbnail.frame(width: compact ? 22 : 34, height: compact ? 22 : 34)
            VStack(alignment: .leading, spacing: 2) {
                Text(item.text)
                    .font(compact ? .callout : .body)
                    .lineLimit(compact ? 1 : 3)
                    .foregroundStyle(item.kind == .link ? Color.janus : .primary)
                if !compact {
                    Text(item.date, format: .relative(presentation: .named, unitsStyle: .abbreviated))
                        .font(.caption).foregroundStyle(.tertiary)
                }
            }
            Spacer(minLength: 0)
        }
    }

    @ViewBuilder private var thumbnail: some View {
        if let image = item.image {
            Image(nsImage: image).resizable().aspectRatio(contentMode: .fill)
                .clipShape(RoundedRectangle(cornerRadius: 5, style: .continuous))
        } else {
            Image(systemName: item.kind == .link ? "link" : "doc.text")
                .font(.system(size: compact ? 10 : 14, weight: .semibold))
                .foregroundStyle(.secondary)
                .frame(maxWidth: .infinity, maxHeight: .infinity)
                .background(Color.primary.opacity(0.07), in: RoundedRectangle(cornerRadius: compact ? 5 : 8, style: .continuous))
        }
    }
}

struct ClipboardView: View {
    let device: Device
    @State private var search = ""
    @State private var copied: UUID?
    private var history: ClipboardHistory { .shared }

    private var items: [ClipboardHistory.Item] {
        search.isEmpty ? history.items : history.items.filter { $0.text.localizedCaseInsensitiveContains(search) }
    }

    var body: some View {
        Group {
            if history.items.isEmpty {
                ContentUnavailableView {
                    Label("Nothing Copied Yet", systemImage: "doc.on.clipboard")
                } description: {
                    Text("Text, links and images you copy on this Mac or on \(device.name) appear here. Passwords are never recorded.")
                }
            } else {
                ScrollView {
                    LazyVStack(spacing: 0) {
                        ForEach(Array(items.enumerated()), id: \.element.id) { index, item in
                            if index > 0 { Divider().padding(.leading, 64) }
                            row(item)
                        }
                    }
                    .padding(.vertical, 6)
                    .cardBackground()
                    .padding(24)
                    .frame(maxWidth: 720)
                    .frame(maxWidth: .infinity)
                }
            }
        }
        .navigationTitle("Clipboard")
        .navigationSubtitle(history.items.isEmpty ? "" : "Last \(history.items.count) copied")
        .searchable(text: $search, placement: .toolbar, prompt: "Search Clipboard")
        .toolbar {
            ToolbarItem(placement: .primaryAction) {
                Button { history.clear() } label: { Label("Clear History", systemImage: "trash") }
                    .disabled(history.items.isEmpty)
            }
        }
    }

    private func row(_ item: ClipboardHistory.Item) -> some View {
        HStack(spacing: 8) {
            ClipboardItemRow(item: item)
            Button(copied == item.id ? "Copied" : "Copy") {
                history.copy(item)
                copied = item.id
                Task { try? await Task.sleep(for: .seconds(1.5)); if copied == item.id { copied = nil } }
            }
            Button("Send to Phone") { history.send(item, to: device) }
                .disabled(!device.isReachable)
            Button { history.remove(item) } label: { Image(systemName: "xmark") }
                .buttonStyle(.borderless)
                .help("Remove from history")
        }
        .controlSize(.small)
        .padding(.horizontal, 16).padding(.vertical, 10)
        .contentShape(Rectangle())
        .onTapGesture(count: 2) { history.copy(item) }
    }
}
